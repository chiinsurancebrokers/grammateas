def load_members_dict() -> Dict[int, Dict]:
    try:
        df = get_all_members()
        return {int(row["id"]): row.to_dict() for _, row in df.iterrows()}
    except Exception:
        return {}


def member_display_name(m: Dict) -> str:
    return f"Αδ∴ {m.get('επώνυμο','')} {m.get('όνομα','')}".strip()


def read_docx_text(path: str) -> str:
    try:
        from docx import Document
        doc = Document(path)
        lines = [p.text.strip() for p in doc.paragraphs if p.text.strip()]
        for table in doc.tables:
            for row in table.rows:
                seen = set()
                for cell in row.cells:
                    cid = id(cell._tc)
                    if cid not in seen and cell.text.strip():
                        lines.append(cell.text.strip())
                        seen.add(cid)
        return "\n".join(lines)
    except Exception as e:
        return f"[Σφάλμα ανάγνωσης: {e}]"


def _unique_cells(row) -> List:
    seen = set()
    cells = []
    for cell in row.cells:
        cid = id(cell._tc)
        if cid not in seen:
            cells.append(cell)
            seen.add(cid)
    return cells


def _write_cell(cell, text: str) -> None:
    text = str(text or "").strip()
    if not text:
        return
    for para in cell.paragraphs:
        if para.runs:
            para.runs[0].text = text
            for r in para.runs[1:]:
                r.text = ""
            return
    if cell.paragraphs:
        cell.paragraphs[0].add_run(text)
    else:
        cell.add_paragraph(text)


def _replace_in_para(para, old: str, new: str) -> bool:
    full = "".join(r.text for r in para.runs)
    if old not in full:
        return False
    new_text = full.replace(old, new)
    if para.runs:
        para.runs[0].text = new_text
        for r in para.runs[1:]:
            r.text = ""
    return True


def _member_full_name(m: Optional[Dict]) -> str:
    if not m:
        return ""
    return f"{m.get('επώνυμο', '')} {m.get('όνομα', '')}".strip()


def _member_full_with_patronymic(m: Optional[Dict]) -> str:
    if not m:
        return ""
    parts = [m.get('επώνυμο', ''), m.get('όνομα', '')]
    pat = m.get('πατρώνυμο', '')
    if pat:
        parts.append(f"του {pat}")
    return " ".join(p for p in parts if p).strip()


def _fmt_date_gr(d: str) -> str:
    from datetime import datetime
    for fmt in ("%Y-%m-%d", "%d/%m/%Y", "%d-%m-%Y"):
        try:
            return datetime.strptime(d, fmt).strftime("%d/%m/%Y")
        except Exception:
            pass
    return d or "——"



    buf = io.BytesIO()
    SimpleDocTemplate(
        buf, pagesize=A4,
        rightMargin=2.5*cm, leftMargin=2.5*cm,
        topMargin=2*cm,     bottomMargin=2.5*cm,
    ).build(story)

from collections import defaultdict
by_cat = defaultdict(list)
for art in ARTICLES:
    by_cat[art["cat"]].append(art)

# Φίλτρο αναζήτησης
def matches(art, q):
    q = q.lower()
    return (q in art["κείμενο"].lower()
            or q in art["τίτλος"].lower()
            or q in art["ref"].lower()
            or q in art["cat"].lower()
            or any(q in t for t in art["tags"]))

total_shown = 0
for cat, arts in by_cat.items():
    if search:
        arts = [a for a in arts if matches(a, search)]
    if not arts:
        continue
    total_shown += len(arts)

    with st.expander(f"{cat}  ·  *{len(arts)} άρθρα*",
                     expanded=bool(search) or show_all):
        for art in arts:
            col1, col2 = st.columns([1, 6])
            with col1:
                st.markdown(
                    f'<div style="background:#1a2a4a;color:white;padding:5px 8px;'
                    f'border-radius:5px;font-size:11px;font-weight:bold;text-align:center;'
                    f'margin-top:4px;">{art["ref"]}</div>',
                    unsafe_allow_html=True
                )
            with col2:
                st.markdown(f"**{art['τίτλος']}**")
                st.markdown(art["κείμενο"])
            st.divider()

if search and total_shown == 0:
    st.warning(f"Δεν βρέθηκαν άρθρα για «{search}»")

